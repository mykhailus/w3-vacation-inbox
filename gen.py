def rec(row):
    i, at, frm, cc, subj, body = row
    return {"id": i, "at": at, "from": frm, "to": ANNA, "cc": cc, "subject": subj, "body": body}


def sent_rec(row):
    i, at, to, cc, subj, body = row
    return {"id": i, "at": at, "from": ANNA, "to": to, "cc": cc, "subject": subj, "body": body}


def md(r):
    return (f"# {r['id']} · {r['subject']}\n\nid: {r['id']}\nfrom: {r['from']}\nto: {r['to']}\ncc: {r['cc']}\n"
            f"date: {r['at'].replace('T', ' ')}\nsubject: {r['subject']}\n---\n\n{r['body']}\n")


def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main():
    assert len(INBOX) == 40 and len(SENT) == 10 and len(CHAT) == 80, (len(INBOX), len(SENT), len(CHAT))
    for name, rows, conv in (("inbox", INBOX, rec), ("sent", SENT, sent_rec)):
        recs = [conv(r) for r in rows]
        assert [r["at"] for r in recs] == sorted(r["at"] for r in recs), name
        write(OUT / f"{name}.jsonl", "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in recs))
        for r in recs:
            write(OUT / name / f"{r['id']}.md", md(r))
    chat = [{"id": f"C{n:03d}", "at": at, "name": who, "text": t} for n, (at, who, t) in enumerate(CHAT, 1)]
    assert [c["at"] for c in chat] == sorted(c["at"] for c in chat), "chat order"
    write(OUT / "chat.jsonl", "".join(json.dumps(c, ensure_ascii=False) + "\n" for c in chat))
    write(OUT / "chat.md", "# Чат «Кадр и Свет»\n\n" + "".join(
        f"[{c['id']}] {c['at'].replace('T', ' ')} {c['name']}: {c['text']}\n\n" for c in chat))
    write(OUT / "notes.md", NOTES)
    write(OUT / "README.md", LEGEND)
    print("ok:", len(INBOX), "inbox,", len(SENT), "sent,", len(chat), "chat")


if __name__ == "__main__":
    main()
